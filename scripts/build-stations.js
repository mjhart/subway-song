#!/usr/bin/env node
// Regenerates stations.js (stop id -> station name) from the MTA's static
// GTFS bundle. The bundle is served without CORS headers, so the browser
// can't fetch it directly; run this when the MTA adds or renames stations.
//
//   node scripts/build-stations.js

const { execFileSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const GTFS_URL = 'https://rrgtfsfeeds.s3.amazonaws.com/gtfs_subway.zip';

function parseCsvLine(line) {
  const cells = [];
  let cell = '', quoted = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quoted) {
      if (c === '"' && line[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { cells.push(cell); cell = ''; }
    else cell += c;
  }
  cells.push(cell);
  return cells;
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'gtfs-'));
const zip = path.join(tmp, 'gtfs.zip');
execFileSync('curl', ['-sSfL', '-o', zip, GTFS_URL]);
const csv = execFileSync('unzip', ['-p', zip, 'stops.txt'], { encoding: 'utf8' });
fs.rmSync(tmp, { recursive: true });

const [header, ...rows] = csv.trim().split(/\r?\n/).map(parseCsvLine);
const col = (name) => header.indexOf(name);
const stations = {};
for (const row of rows) {
  // Parent stations only; platform ids are the parent id plus N or S.
  if (row[col('parent_station')]) continue;
  stations[row[col('stop_id')]] = row[col('stop_name')];
}

const out = path.join(__dirname, '..', 'stations.js');
fs.writeFileSync(
  out,
  '// Generated by scripts/build-stations.js — do not edit by hand.\n'
    + `const STATIONS = ${JSON.stringify(stations, null, 1)};\n`
    + "if (typeof module !== 'undefined' && module.exports) module.exports = STATIONS;\n",
);
console.log(`Wrote ${Object.keys(stations).length} stations to ${path.relative(process.cwd(), out)}`);
